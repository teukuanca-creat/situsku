Sudah hampir sepekan ini Sinabang hujan terus. Polanya bukan hujan deras tanpa henti seharian, tapi hampir setiap hari ada. 

Reda satu dua jam, jalan mulai kering, lalu turun lagi. Kadang cuma gerimis, kadang disertai petir yang menggelegar di atas atap seng.

Padahal di beberapa tulisan saya sebelumnya, saya masih menulis Sinabang dalam kondisi panas terik. 

Saya tidak tahu apakah di daratan Aceh juga begitu. Sempat juga komunikasi dengan teman di daratan, katanya di sana panas terik, saat itu di sini hujan seharian. 

Meskipun secara nasional Indonesia masih memasuki musim kemarau, wilayah Aceh dan sekitarnya (termasuk Perairan Simeulue) saat ini sedang dipengaruhi oleh dinamika atmosfer lokal yang aktif seperti Gelombang Ekuatorial Rossby.

Dalam laporan peringatan dini sepekan terbaru (September 2026), BMKG menetapkan status Siaga untuk wilayah Aceh karena adanya potensi hujan lebat yang dapat disertai kilat/petir, angin kencang, serta gelombang tinggi.

Kalau dilihat dari pengalaman beberapa tahun, memang Pulau Simeulue ini lebih dominan hujannya. Apalagi akhir-akhir ini memang terasa sekali.

## Mitos Bulan "Ber" dan Suhu Malam yang Terasa Hangat
Orang tua kami dulu sering bilang, kalau sudah masuk bulan yang ujungnya ada kata "ber", September, Oktober, November, Desember, itu sudah tanda musim hujan. 
Walaupun itu hanya kebetulan saja, tidak selalu benar. Tapi tahun ini seperti kebetulan pas.

Ada tanda lain yang justru saya rasakan sendiri minggu ini dan lebih akurat.
Kalau suhu di malam hari terasa dingin menusuk, biasanya besoknya akan terik. Sebaliknya, kalau malam terasa hangat dan agak pengap, besoknya pasti hujan.

Beberapa malam terakhir yang saya rasakan memang hangat. Biasanya kalau keluar malam saya wajib pakai jaket, karena angin lautnya dingin. Minggu ini seperti tidak perlu. 

Kemarin saya keluar ke pasar menuju warung kopi cuma pakai kaus oblong saja sudah cukup. Tidak dingin sama sekali. Dan benar, paginya hujan turun lagi.

