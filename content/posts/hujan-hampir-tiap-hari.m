## Dampak yang Paling Terasa: Harga Ikan dan Warung Jadi Sepi
Kekhawatiran hujan lama ini sangat saya rasakan, bukan karena takut basah, tapi efeknya.

Pertama soal harga ikan. Kalau hujan disertai petir seperti ini, dikhawatirkan nelayan tidak berani melaut. Perahu banyak yang sandar di dermaga. Kalau ikan sedikit masuk pasar, harganya pasti naik. Ini siklus yang selalu berulang setiap tahun.

Kedua, ruang gerak jadi terbatas. Mau keluar sore agak malas, karena langit sudah gelap duluan dan petirnya keras.

Ketiga, penggiat UMKM. Jika diperhatikan, banyak kue-kue di tempat titipan tidak habis saat di jemput pemilik ke tempat jasa titip atau warkop.

Daya beli bukan hilang, tapi tertahan. Jualan jadi sepi. Padahal kalau hujan begini, makanan hangat seperti bakso dan mie kuah seharusnya laku, kalau ada yang antar.

### Banjir Sinabang: Dulu di Simpang Lima, Sekarang Pindah ke Air Dingin
Memang Sinabang ini jarang banjir besar yang sampai melumpuhkan kota.

Saya masih ingat betul banjir di era 2000-an. Air sempat menggenangi area Simpang Lima Sinabang hingga Desa Suka Karya.

Kalau saya lihat saat itu, penyebabnya bukan cuma hujan, tapi sungai yang sudah dangkal karena endapan lumpur sampai meluap ke )jalan. Tingginya sampai lutut orang dewasa, motor-motor banyak yang mogok saat melintasinya.

Sekarang, setelah ada pengerukan sungai di titik asal banjir itu, daerah Simpang Lima sudah tidak terlihat banjir lagi. Sudah aman.

Justru kalau hujan durasi lama, air yang tergenang ada di area Desa Air Dingin. Tadi siang saya lewat sana pakai motor, airnya sudah hampir setengah ban dan menutup jalan jalur dua.

Walaupun tidak terlalu tinggi dan cepat surut, tetap saja khawatir dengan perumahan di sekitar yang posisinya lebih rendah. Warga di sana pasti waswas kalau hujan turun lagi malam hari.

## Apa yang Saya Lakukan Biar Tetap Produktif Saat Hujan On-Off Begini
Karena hujannya putus-nyambunh begini, kita tidak bisa menunggu hujan benar-benar berhenti total. Jadi baik untuk kita atur ulang jam kegiatan.

Kalau mau ke pasar atau belanja ikan, pilih berangkat pagi sekali pukul 07.00 Wib, karena biasanya hujan lebat baru mulai pukul 10.00.Wib ke atas. 

Untuk UMKM, dengan opsi pesan lewat WhatsApp saja dan minta diantar, jadi tetap bisa bantu jualan teman tanpa harus keluar saat petir.

Di rumah, kita pastikan selokan depan tidak tersumbat sampah, karena genangan air biasanya terjadi karena aliran drainase yang kurang lancar. 

Dan jangan lupa cabut stopkontak kalau petirnya sudah terlalu dekat, karena dikhawatirkan listrik padam sesaat kalau petir besar.

Pada akhirnya, pulau ini memang mengajarkan satu hal. Kita bisa memprediksi kemarau sampai September di atas kertas, tapi yang menentukan tetap langit di atas Sinabang. Sepekan ini buktinya, hujan hampir tiap hari ada, walau sempat reda lalu turun lagi.
