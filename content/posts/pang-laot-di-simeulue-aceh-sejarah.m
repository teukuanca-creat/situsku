## A. Pendahuluan 
Sektor kelautan Indonesia menyimpan salah satu sistem tata kelola kearifan lokal (indigenous knowledge) paling terstruktur di dunia.

Di Provinsi Aceh, kehidupan sosial-kemasyarakatan tidak hanya diatur oleh birokrasi pemerintahan formal, melainkan dibingkai oleh tatanan adat yang terikat erat dalam norma Adat Bak Po Teumeureuhom, Hukum Bak Syiah Kuala.

Dalam tatanan masyarakat Aceh, struktur adat hadir secara hierarkis dan fungsional. Masyarakat mengenal Mukim sebagai entitas adat yang membawahi beberapa Gampong (desa), 

Keujreun Blang di sektor pengairan pertanian, hingga Panglima Laot (Pang Laot) yang memegang mandat tertinggi dalam tata kelola wilayah pesisir dan perikanan tangkap.

Integrasi antara struktur adat dan hukum formal inilah yang membuat tata kehidupan sosial-kemaritiman Aceh, khususnya di wilayah kepulauan seperti Simeulue, tetap kokoh melintasi zaman.

## B. Sejarah Awal Panglima Laot: Dari Era Kesultanan hingga Zaman Modern
​Keberadaan Panglima Laot bukan merupakan produk hukum baru, melainkan pranata adat yang telah mengakar selama lebih dari empat abad.

### ​1. Masa Kesultanan Aceh Darussalam (Abad ke-16 – 17)
Menurut catatan sejarah, lembaga Panglima Laot sudah mengakar sejak masa pemerintahan Sultan Iskandar Muda (1607–1636).

Kala itu, Panglima Laot memegang peranan krusial dalam menjaga stabilitas wilayah maritim Aceh, yang mencakup tiga fungsi utama:

- **​Sektor Perdagangan:** Menarik cukai pelabuhan dari kapal-kapal dagang asing yang berlabuh.
- **​Sektor Pertahanan:** Menjadi perpanjangan tangan kesultanan dalam memobilisasi nelayan untuk mengamankan laut dari gangguan luar.
- **Sektor Adat:** Menetapkan tata cara melaut dan menangkap ikan demi mencegah timbulnya gesekan antar nelayan.

### 2. Masa Kolonial Belanda dan Pendudukan Jepang
​Ketika Belanda menginvasi Aceh pada akhir abad ke-19, struktur Panglima Laot mengalami penyempitan peran. Pemerintah kolonial menghapus fungsi militer dan fiskal Panglima Laot untuk melemahkan kekuatan maritim Aceh.

Kendati demikian, fungsi Panglima Laot sebagai hakim adat (mediator) dan penegak Hukum Adat Laot di tingkat kuala/muara tetap dipertahankan secara swadaya oleh masyarakat nelayan setempat karena efektivitasnya dalam menjaga ketertiban.

### ​3. Masa Pasca-Kemerdekaan hingga Era Reformasi
​Pasca-kemerdekaan Indonesia, kelembagaan ini sempat berjalan secara informal tanpa payung hukum negara yang spesifik.

Baru pada tahun 1970-an, para pemangku adat laut di Aceh mulai melakukan konsolidasi kembali.

Musyawarah Besar (Mubes) Panglima Laot Se-Aceh pertama yang digelar pada tahun 1972 menjadi tonggak awal modernisasi organisasi adat ini tanpa menghilangkan nilai-nilai tradisionalnya.

## C. ​Transformasi Dasar Hukum Panglima Laot: Nasional hingga Kabupaten Simeulue
​Secara yuridis, eksistensi Panglima Laot memiliki landasan hukum yang sangat kuat, bertransformasi dari norma lisan menjadi bagian dari hukum positif Indonesia.

### ​1. Landasan Hukum Tingkat Nasional & Provinsi
1). Undang-Undang Nomor 44 Tahun 1999, tentang Penyelenggaraan Keistimewaan Provinsi Daerah Istimewa Aceh (mengakui penyelenggaraan kehidupan adat).
2). Undang-Undang Nomor 11 Tahun 2006, tentang Pemerintahan Aceh (UUPA):
- ​Pasal 98 (ayat1 dan 2): Lembaga adat berfungsi dan berperan sebagai wahana partisipasi masyarakat dalam penyelenggaraan Pemerintahan Aceh dan pemerintahan kabupaten/kota. Penyelesaian masalah sosial kemasyarakatan secara adat ditempuh melalui lembaga adat.
- Pasal 98 ayat (3): Memberikan kewenangan atribusi kepada Pemerintah Aceh untuk merinci dan menetapkan lembaga adat apa saja yang sah secara hukum melalui produk Qanun.
- Pasal 156: Memberikan hak bagi Pemerintah Aceh untuk mengelola sumber daya alam (termasuk kelautan) secara mandiri dengan tetap menghormati kearifan lokal.
3). Qanun Provinsi Aceh Nomor 9 Tahun 2008, tentang Pembinaan Kehidupan Adat dan Adat Istiadat.
4). Qanun Provinsi Aceh Nomor 10 Tahun 2008, tentang Lembaga Adat.

### ​2. Dasar Hukum Khusus di Kabupaten Simeulue
Di tingkat wilayah Kabupaten Simeulue, aturan teknis dan pengakuan hukum bagi Panglima Laot dijabarkan melalui beberapa peraturan daerah berikut:
1). Peraturan Bupati Simeulue Nomor 32 Tahun 2018 tentang Lembaga Hukum Adat Laot dalam Kabupaten Simeulue. Aturan ini mendefinisikan struktur, kedudukan, tugas, serta peran Panglima Laot di wilayah pesisir sengketa dan kelautan lokal.
2). Peraturan Bupati Simeulue Nomor 36 Tahun 2018 tentang Lembaga Hukum Adat Laot dalam Kabupaten Simeulue. Peraturan ini mengatur lebih detail mengenai mekanisme Musyawarah Umum Panglima Laot Lhok, kode etik, penyelesaian perkara, hingga pemberhentian pengurus.
3). Qanun Kabupaten Simeulue Nomor 30 Tahun 2003 tentang Perlindungan dan Pelestarian Kawasan Perairan Pantai dan Pulau-Pulau. Regulasi ini menjadi landasan bagi Panglima Laot dalam menjalankan fungsi ekologis atau menjaga kelestarian ekosistem laut setempat.

## D. Eksistensi dan Kedudukan Sekretariat Panglima Laot di Simeulue
​Sebagai wilayah yang dikelilingi Samudera Hindia dengan garis pantai sepanjang ratusan kilometer, Kabupaten Simeulue menempatkan Panglima Laot sebagai garda terdepan tata kelola pesisir.

### 1. Hierarki dan Struktur Organisasi Panglima Laot
#### 1). Panglima Laot Kabupaten: 
Dipimpin oleh 1 (satu) orang ketua/pengurus utama yang mengoordinasikan wilayah hukum adat laut di tingkat kabupaten.

#### 2). Panglima Laot Lhok (Tingkat Kecamatan/Kuala/Teluk):
Berkedudukan di pangkalan pendaratan ikan atau wilayah pesisir tempat aktivitas nelayan berlangsung, tersebar di berbagai kecamatan pesisir namun jumlah pastinya bersifat dinamis berdasarkan pembentukan kawasan lhok lokal.

#### 3). Panglima Laot Desa/Gampong:
Sebagian wilayah pesisir di Simeulue juga mengenal struktur adat laut di tingkat desa yang membawahi kelompok nelayan setempat.

### 2. Struktur & Pusat Operasional Kelembagaan
#### 1). Tingkat Kabupaten (Pusat Koordinasi & Strategis):
- Kedudukan: Berkedudukan di Sinabang, yang merupakan pusat pemerintahan sekaligus ibu kota Kabupaten Simeulue.
- Titik Koordinasi Pesisir: Kantor operasional idealnya berada di sekitar kawasan Pelabuhan Perikanan Pantai (PPP) Teluk Sinabang atau Pelabuhan Pendaratan Ikan (PPI) Lugu. Kawasan PPI Lugu merupakan urat nadi aktivitas perikanan skala besar di Simeulue, menjadikannya lokasi strategis bagi Panglima Laot Kabupaten untuk berkoordinasi langsung dengan Dinas Kelautan dan Perikanan (DKP) Kabupaten Simeulue serta instansi kemaritiman lainnya.
- Sekretariat Kelembagaan Adat: Selain di area pelabuhan, sekretariat juga dapat ditempatkan di Kompleks Pusat Kelembagaan Adat Kabupaten. Penempatan ini lazim dilakukan di Aceh guna keperluan administrasi formal serta penyelenggaraan sidang adat besar (Duek Pakat) yang melibatkan Majelis Adat Aceh (MAA) setempat.

#### 2). Tingkat Lhok (Pusat Pelayanan & Tata Kelola Lapangan):
- Pusat Operasional: Berkantor langsung di pangkalan muara, dermaga, atau kawasan Tempat Pelelangan Ikan (TPI) pada masing-masing wilayah hukum adat Lhok.
- Dinamika Interaksi dan Fungsi: Ciri utama dari kantor operasional tingkat Lhok adalah interaksi langsung secara harian antara Panglima Laot Lhok dengan para Pawang (kapten kapal) dan masyarakat nelayan.
- Fungsi utama mereka di lapangan meliputi:
**Peradilan Adat Laut:** Menyelesaikan perselisihan atau sengketa antar-nelayan yang terjadi di laut atau di area pendaratan ikan.
**Kepatuhan Hukum Adat:** Mengatur pantangan hari melaut (seperti larangan melaut pada hari Jumat, hari raya keagamaan, atau hari kenduri laut) serta mengawasi tata cara penangkapan ikan yang ramah lingkungan.
**Sistem Kedaruratan:** Menjadi pusat informasi dan penanganan awal saat terjadi laporan darurat, seperti kecelakaan laut, kapal rusak, atau nelayan yang hilang di laut

### 3. ​Tata Kerja, Tanggung Jawab, Pemilihan dan Masa Jabatan
​Berikut adalah rincian mekanisme tata kerja serta aturan kelembagaan Panglima Laot:
#### 1). Garis Pertanggungjawaban:
- Tanggung Jawab Adat: Musyawarah Nelayan: Keputusan tertinggi dan bentuk pertanggungjawaban moral-adat berada pada musyawarah masyarakat nelayan atau tingkat lhok.
- Peran Pawang: Menjaga kepatuhan terhadap hukum adat laut (hukum adat laot).
  
#### 2). Koordinasi Administratif:
- Pemerintah Daerah: Berkoordinasi dengan Bupati melalui Dinas Kelautan dan Perikanan (DKP).
- Pembinaan Adat: Bersinergi dengan Majelis Adat Aceh (MAA) dalam hal kelembagaan adat.

#### ​3). Mekanisme Pemilihan:
- Tingkat Lhok (Kawasan/Pelabuhan Perikanan): Dipilih langsung melalui musyawarah oleh para pawang boat, nelayan, serta pemilik alat tangkap setempat.
- Tingkat Kabupaten/Kota & Provinsi: Dipilih melalui musyawarah antarpengurus/perwakilan Panglima Laot dari tingkat di bawahnya.
- Pelibatan Unsur Lain: Tokoh masyarakat pesisir dan unsur pemerintah lokal (seperti Dinas Perikanan atau mukim/kecamatan) umumnya hadir atau dilibatkan dalam kapasitas koordinasi, pengukuhan, serta kemitraan, sementara hak suara utama tetap berada di tangan komunitas nelayan.

#### ​4). Kriteria dan Syarat Umum Calon Panglima Laot:
- Beragama Islam: Wajib taat beragama dan mampu membaca Al-Qur'an.
- Pengalaman Bahari: Berpengalaman di laut, pernah atau sedang menjadi pawang laot/pawang boat, serta mengerti navigasi dan seluk-beluk kelautan.
- Pemahaman Hukum Adat: Menguasai aturan, pantangan, dan Hukum Adat Laut beserta penyelesaian sengketa.
- Karakter Pribadi: Bersifat jujur, adil, bijaksana, dan memiliki kepedulian tinggi terhadap kesejahteraan nelayan.
- Persyaratan Administratif Tambahan: Umumnya merupakan Warga Negara Indonesia (WNI), laki-laki yang sudah berkeluarga, bisa baca-tulis, serta berdomisili di wilayah hukum adat setempat.

#### 5). ​Ketentuan Masa Jabatan Panglima Laot:
- Sistem Pemilihan: Dipilih secara demokratis melalui musyawarah mufakat oleh komunitas nelayan setempat (seperti di tingkat lhok atau kabupaten).
- Durasi Periode: Di beberapa wilayah atau tingkat kabupaten/kota, masa jabatan diatur selama 5 tahun atau 6 tahun. Sebagai contoh, regulasi di beberapa kabupaten/kota menetapkan masa bakti 6 tahun, sementara acuan administratif adat lainnya menggunakan periode 5 tahun.
- Hak Pilih Kembali: Dapat dipilih kembali untuk satu periode berikutnya jika masih dipercaya oleh masyarakat nelayan.
- Dasar Hukum Adat: Keberadaan dan penguatan kelembagaan ini berlandaskan pada Undang-Undang Pemerintahan Aceh (UUPA) serta qanun pembinaan adat.

### 4. ​Sistem Penganggaran dan Pembiayaan
​Untuk menjalankan roda organisasi adat, Panglima Laot memanfaatkan sistem pembiayaan berbasis kemandirian komunitas yang disinergikan dengan dukungan pemerintah:
- ​Retribusi Adat (Kanduri Laot & Hak Lhok): Bagian kecil dari hasil lelang ikan atau kontribusi kapal/pukat yang mendarat di Lhok setempat sesuai kesepakatan musyawarah adat.
- Anggaran APBK (Dana Transfer Daerah): Alokasi hibah atau bantuan operasional lembaga adat dari APBK Simeulue melalui anggaran pembinaan kelembagaan adat pada Dinas Kelautan dan Perikanan serta Majelis Adat Aceh (MAA).
- ​Alokasi Dana Desa (ADD/APBG): Pada beberapa Gampong pesisir, penguatan kegiatan adat laut didukung melalui alokasi dana desa yang berfokus pada pelestarian kearifan lokal pesisir.

### 5. ​Tugas, Wewenang, dan Spektrum Masalah Pengelolaan Pesisir
​Panglima Laot memikul tanggungjawab yang luas dalam menjaga stabilitas sosio-ekonomi dan ekologi pesisir Simeulue, meliputi:

#### ​1). Penegakan Hukum Adat Laot dan Hari Pantang Melaut
​Mengatur Hari Pantang Melaut, misalnya:
- Hari Jumat mulai Kamis malam,
- Hari Raya Idul Fitri/Idul Adha,
- Hari Kemerdekaan 17 Agustus, dan Peringatan Tsunami 26 Desember.

​Sanksi adat bagi yang melanggar dapat berupa penyitaan seluruh hasil tangkapan, larangan melaut selama 3 hingga 7 hari, hingga pelaksanaan syukuran adat secara mandiri oleh pelanggar.

#### ​2). Perlindungan Ekosistem & Konservasi Sumber Daya Laut
- ​Pelarangan Illegal Fishing: Menjadi benteng terdepan menolak penggunaan bom ikan, racun sianida, serta pukat harimau (trawl) yang merusak terumbu karang di sekitar kepulauan Simeulue.
- ​Perlindungan Satwa Dilindungi. Melarang penangkapan penyu, pengambilan telur penyu secara ilegal, dan perusakan kawasan padang lamun serta hutan mangrove.

#### ​3). Penyelesaian Konflik (Hakim Peradilan Adat)
​Jika terjadi tabrakan perahu, perebutan rumpon, atau pelanggaran jalur tangkap antar-nelayan lokal maupun nelayan luar, Panglima Laot bertindak sebagai hakim penyelesai sengketa pertama (restorative justice) tanpa langsung membawa masalah ke kepolisian.

#### ​4). Isu dan Masalah Krusial di Pesisir Simeulue
a). ​Saat ini, Panglima Laot Simeulue dihadapkan pada beberapa tantangan modern:
- Maraknya nelayan Luar dan kapal modern
- Kapal besar dari luar daerah atau berskala industri sering masuk ke zona pancing tradisional nelayan lokal Simeulue.

Menimbulkan gesekan atau sengketa adat karena dianggap meresahkan dan merugikan hasil tangkapan nelayan kecil.

Penyelesaian sengketa ini kerap diserahkan kepada lembaga adat Panglima Laot melalui penegakan hukum adat laut.

b). Perubahan Iklim dan Cuaca Ekstrem
Gelombang tinggi dan cuaca buruk tahunan menghambat aktivitas melaut serta menaikkan biaya operasional akibat jarak tempuh ikan yang bergeser.

Membutuhkan koordinasi mitigasi dan keselamatan pelayaran (safety at sea) yang lebih kuat.

## E. ​Kesimpulan: Menjaga Kedaulatan Laut Melalui Akar Adat
​Dari rekam sejarah panjang Kesultanan Aceh hingga pengakuan formal dalam Qanun Kabupaten Simeulue, Panglima Laot telah membuktikan dirinya bukan sekadar simbol tradisi yang kaku, melainkan sebuah sistem tata kelola maritim yang adaptif, demokratis, dan berkelanjutan.

​Bagi masyarakat Kepulauan Simeulue, laut bukanlah pemisah antar-daratan, melainkan piring kehidupan dan halaman rumah yang wajib dijaga kehormatannya.

Melalui kepemimpinan Panglima Laot, nilai-nilai kearifan lokal seperti tradisi Smong, penghormatan terhadap alam, dan semangat gotong royong terbukti mampu menjaga kelestarian biota laut seperti lobster, gurita, dan terumbu karang Simeulue tetap lestari hingga hari ini.

​Menjunjung tinggi adat laut berarti menjaga masa depan generasi Simeulue. Di tengah arus modernisasi dan tantangan ekonomi global, penguatan kelembagaan Panglima Laot adalah kunci mutlak untuk memastikan bahwa kekayaan pesisir Simeulue tetap menjadi tuan rumah di negerinya sendiri, dikelola dengan ilmu pengetahuan modern, tanpa pernah mencabut akar kearifan adat nenek moyang.

