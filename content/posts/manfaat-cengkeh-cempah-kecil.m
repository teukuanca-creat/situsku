### Perbandingan Jual Mentah vs Olahan

Jika petani menjual 10 kg cengkeh basah, hasilnya sekitar **Rp280.000**.

Jika 10 kg cengkeh basah dikeringkan menjadi sekitar 3 kg kering, nilainya sekitar **Rp315.000–Rp363.000**.

Jika diolah menjadi minyak atsiri, 10 kg cengkeh basah bisa menghasilkan sekitar 100–150 ml minyak dengan nilai **Rp200.000–Rp350.000**.

Artinya, pengolahan sederhana bisa meningkatkan nilai jual hingga dua kali lipat.

## G. Tutorial: Menyuling Minyak Cengkeh Skala Rumahan

Bagi yang ingin mencoba, berikut langkah sederhana:

### Alat yang dibutuhkan:

- Panci besar atau dandang
- Pipa tembaga atau selang tahan panas
- Botol penampung
- Air bersih
- Daun cengkeh kering secukupnya

### Langkah:

1. Masukkan daun atau bunga cengkeh kering ke dalam panci berisi air.
2. Tutup rapat panci, sambungkan pipa ke lubang uap.
3. Panaskan di atas kompor dengan api sedang.
4. Uap akan mengalir melalui pipa dan mengembun.
5. Tampung tetesan minyak dalam botol.
6. Pisahkan minyak dari air—minyak mengambang di atas.

Proses ini membutuhkan ketelitian dan waktu. Tapi hasilnya nyata: minyak atsiri dengan nilai jual tinggi.

## H. Tantangan Usia Tanaman dan Solusinya

Banyak pohon cengkeh di Simeulue yang sudah berusia tua.

Tantangan umum:

- Pohon di atas 25–30 tahun
- Cabang rusak akibat angin
- Tanah kelelahan
- Serangan hama penggerek batang

Solusinya:

- Pemangkasan rutin
- Pemupukan organik
- Peremajaan tanaman
- Pengendalian hama terpadu

Peremajaan menjadi kunci. Tanpa regenerasi pohon, produksi lokal akan terus menurun.

