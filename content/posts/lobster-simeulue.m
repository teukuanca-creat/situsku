Ia juga harus menjadi pengingat.

Dulu kami bermain di pinggir Teluk Sinabang tanpa pernah berpikir tentang istilah stok sumber daya, habitat, keberlanjutan, rantai pasok atau pasar global.

Kami hanya tahu bahwa ketika air surut, ada lobster di balik batu.

Sekarang, setelah mengetahui bahwa lobster tersebut memiliki nilai ekonomi tinggi dan menjadi bagian dari perdagangan nasional bahkan internasional, kita tentu melihatnya dengan cara berbeda.

Kalau lobster terlalu banyak diambil ketika masih kecil, jumlahnya bisa berkurang.

Kalau habitatnya terganggu, tempat hidupnya ikut berubah.

Kalau lobster bertelur ikut ditangkap, regenerasinya juga terganggu.

Karena itu, masa depan lobster Simeulue tidak cukup hanya mengandalkan besarnya permintaan pasar.

Yang lebih penting adalah bagaimana sumber daya tersebut tetap tersedia.

Kita tentu ingin lobster Simeulue tetap mempunyai nilai ekonomi.

Tetapi kita juga ingin anak-anak Simeulue beberapa puluh tahun mendatang masih bisa melihat kehidupan laut di sekitar pulau ini.

