# Lobster Simeulue: Hasil Laut yang Terlihat Sejak Dahulu 

Ada satu masa dalam hidup yang tidak pernah hilang dari ingatan: masa kecil dengan permainan tanpa gawai, tidak membutuhkan tempat khusus, dan hampir setiap sudut kampung bisa menjadi arena bermain.

Tumbuh di sekitar Teluk Sinabang, khususnya kawasan Simpang Lima, pelabuhan kargo lama merupakan salah satu tempat bermain terfavorit.

Tempat itu juga menjadi lapangan bermain. tempat bermain bola, petak umpet, sampai menaiki kelahar (sebutan lokal untuk kendaraan sederhana dari kayu yang menggunakan roda lahar) yang ditunggangi secara bergantian.

### Dua Antenna Panjang di Balik Batu

Dari atas tanggul, saya sering melihat dua antenna panjang berduri menjulur dari balik batu. Ada ukuran kecil, ada pula ukuran besar. Itulah dia sungut panjang **lobster** yang sering terlihat sejak kecil lagi.

Menangkapnya bukan pekerjaan mudah. Lobster sangat responsif terhadap gerakan air. Kalau tangan bergerak terlalu cepat atau permukaan air terganggu, lobster bisa langsung menghilang. 

Gerakannya cepat sekali, dalam hitungan detik saja, ia menghilang meninggalkan jejak air yang menjadi keruh.

Kami harus belajar bergerak perlahan. Kadang kami hanya menunggu ketika lobster sedang lengah. Ketika kumisnya sedikit muncul ke permukaan air, barulah dia berhasil ditangkap.

Betapa senangnya hati saat tangan kecil ini menggenggam seekor lobster hasil tangkapan sendiri dipinggiran tanggul pelabuhan kargo simpang lima. Sangking senangnya, kami tidak memperdulikan bahaya sengatan badan hingga sungutnya yang berduri itu.

## Lobster dan Nama Simeulue

Seiring bertambahnya usia, saya baru sadar kalau Simeulue memang sudah lama terkenal dengan hasil lautnya. Pantas saja sejak dulu kami begitu mudah menemukan lobster.

Bahkan, perdagangan lobster bukan sesuatu yang baru jika merujuk dari beberapa informasi perdagangan lobster Simeulue.

Sebuah kajian mengenai rantai pasok mencatat bahwa lobster Simeulue telah dipasarkan ke berbagai daerah seperti Jakarta dan Medan, kemudian diteruskan ke pasar luar negeri seperti Taiwan, Hong Kong, Shanghai, Tiongkok dan Singapura.

Sumber lain yang membahas potensi perikanan Simeulue juga menyebut lobster sebagai salah satu hasil laut yang telah membuat nama daerah ini dikenal hingga tingkat nasional dan mancanegara.

Artinya, ketika membicarakan lobster Simeulue hari ini, kita sedang membicarakan komoditas yang memiliki sejarah cukup panjang.

### Jenis Lobster yang Ditemukan di Perairan Simeulue

Yang menarik, lobster di Simeulue ternyata bukan hanya satu jenis.

Penelitian yang diterbitkan pada 2024 berdasarkan penelitian lapangan tahun 2023 mencatat **6 spesies lobster dari genus Panulirus** di perairan Simeulue.

Penelitian tersebut melakukan pengamatan di beberapa wilayah perairan Simeulue, antara lain Busung, Kampung Air, Teupah Selatan, dan Alafan.

1. Panulirus homarus
2. Panulirus longipes
3. Panulirus penicillatus
4. Panulirus versicolor
5. Panulirus ornatus
6. Panulirus polyphagus

Dalam sebutan perdagangan dan sebutan masyarakat, nama lobster sering lebih dikenal dengan nama lokal:

1. Lobster Pasir
2. Lobster Batu
3. Lobster Bambu
4. Lobster Mutiara
5. Lobster Batik
6. Lobster Pakistan.

Karena nama lokal dan nama ilmiah tidak selalu berpadanan satu banding satu dalam percakapan sehari-hari, penyebutan jenis sebaiknya tetap mengacu pada identifikasi biologis ketika membahas spesies.

Hal ini penting karena lobster yang terlihat berbeda warna atau bentuk belum tentu otomatis merupakan spesies yang berbeda.

### Kisaran Harga Lobster Simeulue Sekarang

Pertanyaan ini menarik karena harga lobster memang tidak memiliki satu angka tetap.

Harga dapat berubah berdasarkan;
- Jenis,
- Ukuran,
- Kondisi lobster,
- Musim,
- Kualitas,
- Tujuan pasar,
- Hingga jalur distribusinya.

Berdasarkan data historis perdagangan lokal pada Februari 2023, pasar lobster di wilayah ini menunjukkan karakteristik diferensiasi harga yang sangat dipengaruhi oleh jenis dan ukuran (kategori bobot) komoditas.

Fenomena fluktuasi harga ini dipengaruhi oleh dinamika musiman, di mana pada periode tersebut nelayan setempat cenderung mengalihkan fokus kerja ke sektor perkebunan untuk memanen cengkeh, sehingga berdampak pada berkurangnya pasokan lobster di tingkat pengepul.

Catatan transaksi pada periode tersebut menunjukkan bahwa:
- Lobster batu dengan ukuran 2 hingga 5 ons per ekor diperdagangkan pada kisaran harga Rp300.000 per kilogram.
- Sementara itu, lobster pasir dengan ukuran komersial yang lebih kecil (1,7 hingga 2 ons) dihargai sebesar Rp250.000 per kilogram.

Sistem transaksi untuk kedua jenis lobster konsumsi ini seluruhnya berbasis berat standar kilogram, berbeda dengan perdagangan Benih Bening Lobster (BBL) yang umumnya dihitung per ekor.

Di sisi lain, lobster mutiara, yang oleh masyarakat lokal sering dijuluki "lobster maradona" tetap memegang posisi sebagai varietas dengan nilai ekonomi tertinggi: 

- Berada pada kisaran harga Rp550.000 per kilogram untuk ukuran standar, harga jenis mutiara ini bahkan kerap melonjak melampaui Rp1.000.000 per kilogram ketika permintaan ekspor meningkat dan ukuran lobster memenuhi kriteria pasar internasional.

Perbedaan harga yang signifikan antarvarietas ini menegaskan bahwa segmentasi pasar lobster di Simeulue sangat sensitif terhadap kualitas biologis dan preferensi pasar global.

#### Fakta Pendukung
Berdasarkan data riset pemasaran lokal di Simeulue serta statistik perdagangan global dari UN Comtrade.
- **Riset Lapangan Simeulue (Data Primer 2025):** Studi mengenai Efisiensi Saluran Pemasaran Lobster Simeulue mengonfirmasi bahwa penentuan harga sangat dikendalikan oleh pengepul berdasarkan jenis, ukuran karapas, dan kualitas fisik lobster. Angka kisaran Rp260.000/kg hingga Rp450.000/kg mencerminkan harga riil pada jalur transaksi nelayan lokal untuk jenis lobster non-mutiara (seperti lobster batu dan bambu).
- **Statistik UN Comtrade (Pembaruan 2026):** Berdasarkan analisis data perdagangan terbaru yang dirangkum oleh Selina Wamucii, nilai satuan ekspor (export unit value) rata-rata untuk komoditas lobster asal Indonesia memang tercatat sebesar US$65,85/kg.

#### Mengapa Angkanya Berbeda Jauh?
Tingginya harga ekspor dibanding harga di tingkat nelayan disebabkan oleh:

- **Biaya Logistik Tinggi:** Pengiriman dari pulau terluar seperti Simeulue ke Jakarta atau Medan memerlukan transportasi udara khusus.
- **Risiko Kematian (Live Handling):** Lobster diekspor dalam keadaan hidup, sehingga membutuhkan fasilitas penampungan beroksigen dengan tingkat mortalitas tinggi selama perjalanan.
- **Margin Rantai Pasok:** Adanya bagi hasil margin keuntungan di tingkat pengepul lokal, pedagang besar antar-pulau, hingga eksportir final.






## Apakah Lobster Simeulue Sekarang Masih Ada di Pinggir Teluk?

Di sinilah nostalgia masa kecil saya mulai bertemu dengan kenyataan hari ini.

Ketika masih kecil, saya bisa melihat lobster hanya dengan memperhatikan celah-celah batu dan tanggul ketika air surut.
Sekarang ceritanya berbeda.

Sebuah laporan Antara pada 2021 menyebut nelayan Simeulue mengatakan lobster semakin sulit ditemukan dan sebagian harus dicari di perairan yang lebih dalam. 

Dalam laporan tersebut, seorang pedagang lobster menyebut bahwa lobster saat itu sudah berada di laut yang lumayan dalam sehingga membutuhkan alat bantu pernapasan untuk mendapatkannya.

Kondisi tersebut tentu tidak bisa langsung disimpulkan sebagai akibat tunggal dari satu faktor.
Pada umunya yang memengaruhi keberadaan lobster:
* Perubahan habitat,
* Tekanan penangkapan,
* Musim, kondisi laut dan berbagai faktor ekologis dapat .

Namun ada satu hal yang menarik dari penelitian yang lebih baru.
Penelitian tentang hasil tangkapan lobster Simeulue tahun 2023 menemukan lobster di sejumlah wilayah perairan, termasuk Busung, Kampung Air, Teupah Selatan dan Alafan.

Artinya, lobster masih menjadi bagian dari sumber daya perikanan Simeulue.

Hanya saja, pengalaman masa kecil saya yang bisa menemukan lobster di bagian teluk yang dangkal mungkin memang tidak lagi sama dengan kondisi sekarang.

Teluk yang dahulu terasa begitu dekat dengan kehidupan lobster, sekarang harus kita lihat dengan perspektif yang berbeda.

## Dari Teluk Sinabang ke Pasar Dunia

Kalau dulu saya mengenal lobster dari dua kumis panjang yang muncul di balik batu, dunia sekarang mengenalnya sebagai komoditas bernilai tinggi.

Pasarnya bukan lagi sekadar Sinabang.
Lobster bisa bergerak dari nelayan menuju pengepul, kemudian ke pasar antardaerah dan selanjutnya memasuki jaringan perdagangan internasional.

Kajian mengenai pemasaran lobster Simeulue yang terbit pada akhir 2025 menunjukkan bahwa pemasaran ke luar daerah, seperti Jakarta, memiliki margin lebih tinggi tetapi biaya logistik juga lebih besar.

Dalam penelitian tersebut:
- Farmer's share pada jalur lokal mencapai 80%,
- Sedangkan jalur Jakarta sekitar 51,43% karena adanya tambahan biaya transportasi, penanganan dan logistik.

Ini merupakan tantangan klasik daerah kepulauan. Lobster memang bernilai tinggi, tetapi Simeulue berada jauh dari pusat pasar.

Lobster merupakan komoditas hidup yang membutuhkan penanganan khusus. Semakin panjang perjalanan, semakin besar pula kebutuhan terhadap sistem penyimpanan, transportasi dan pengelolaan kualitas.

Karena itu, nilai lobster tidak hanya ditentukan oleh berapa kilogram yang berhasil ditangkap.

Nilainya juga ditentukan oleh seberapa baik lobster tersebut dapat dipertahankan kualitasnya sampai ke pembeli.

## Bagaimana Prospek Lobster di Pasar Dunia?

Kalau melihat pasar global, prospek lobster masih cukup menarik.

FAO GLOBEFISH melaporkan bahwa perdagangan lobster dunia pada 2025 mencapai sekitar:
- **187.560 ton dengan nilai US$7,35 miliar**.
- Volume tersebut turun 2,9 persen dibandingkan 2024,
- Tetapi nilai perdagangannya justru meningkat 14,4 persen.

Angka tersebut menunjukkan sesuatu yang penting: meskipun volume perdagangan tidak selalu meningkat, nilai ekonominya tetap sangat kuat.

### Pasar Asia menjadi salah satu penggerak utama.

Tiongkok, misalnya, mengimpor sekitar **67.600 ton lobster pada 2025**, meningkat 13 persen dibandingkan tahun sebelumnya. Vietnam menjadi salah satu pemasok yang mengalami pertumbuhan sangat cepat, terutama untuk lobster duri tropis hidup.

FAO juga mencatat prospek jangka panjang pasar lobster tetap optimistis, dengan pertumbuhan sekitar **7–8 persen per tahun hingga 2033** dalam analisis pasar yang mereka rujuk. Permintaan dari sektor restoran dan pangan premium menjadi salah satu pendorongnya.

### Tetapi pasar global juga mempunyai tantangan.

Harga lobster hidup dapat berubah mengikuti pasokan, permintaan, biaya logistik, kebijakan perdagangan dan persaingan antarnegara.

Sebagai gambaran, analisis perdagangan lobster menunjukkan harga rata-rata lobster duri hidup yang diimpor Tiongkok turun dari sekitar **US$60/kg pada 2023 menjadi US$39/kg pada 2025**, antara lain karena perubahan komposisi pasokan dan meningkatnya produk dengan harga lebih rendah.

Jadi prospeknya memang besar, tetapi bukan berarti harga akan selalu naik.

## Lobster Simeulue dan Tantangan Menjaga Laut

Di sinilah saya merasa nostalgia terhadap lobster masa kecil tidak cukup hanya menjadi cerita tentang sesuatu yang pernah ada.

Ia juga harus menjadi pengingat.

Dulu kami bermain di pinggir Teluk Sinabang tanpa pernah berpikir tentang istilah stok sumber daya, habitat, keberlanjutan, rantai pasok atau pasar global.

Kami hanya tahu bahwa ketika air surut, ada lobster di balik batu.

Sekarang, setelah mengetahui bahwa lobster tersebut memiliki nilai ekonomi tinggi dan menjadi bagian dari perdagangan nasional bahkan internasional, kita tentu melihatnya dengan cara berbeda.

Kalau lobster terlalu banyak diambil ketika masih kecil, jumlahnya bisa berkurang.

Kalau habitatnya terganggu, tempat hidupnya ikut berubah.

Kalau lobster bertelur ikut ditangkap, regenerasinya juga terganggu.

Karena itu, masa depan lobster Simeulue tidak cukup hanya mengandalkan besarnya permintaan pasar.

Yang lebih penting adalah bagaimana sumber daya tersebut tetap tersedia.

Kita tentu ingin lobster Simeulue tetap mempunyai nilai ekonomi.

Tetapi kita juga ingin anak-anak Simeulue beberapa puluh tahun mendatang masih bisa melihat kehidupan laut di sekitar pulau ini.

## Lobster yang Mengingatkan Saya pada Masa Kecil

Setiap kali mendengar kata lobster, ingatan saya bukan langsung tertuju pada restoran mahal.

Saya justru teringat Teluk Sinabang.

Teringat Simpang Lima.

Teringat pelabuhan kargo yang dahulu menjadi lapangan bermain kami.

Teringat bola, petak umpet dan *kelahar* yang kami tunggangi bergantian.

Kemudian ketika malam tiba, air *Malasin* mulai surut.

Kami berdiri di sekitar tanggul.

Air teluk yang tenang menjadi tempat kami mencari sesuatu yang sebenarnya pada saat itu belum kami pahami nilainya.

Dari balik batu muncul dua kumis panjang.

Kami bergerak pelan.

Sedikit saja salah bergerak, lobster itu melesat dan meninggalkan air yang keruh.

Begitulah lobster yang saya kenal ketika kecil.

Sederhana.

Liar.

Dan menjadi bagian dari pemandangan sehari-hari.

Tetapi setelah beranjak dewasa, momen itu perlahan menghilang.

Entah karena saya yang sudah jarang memperhatikan.

Atau memang kondisinya sudah berubah.

Cerita dari beberapa teman yang masih dekat dengan laut pun menguatkan perasaan tersebut: lobster yang dahulu relatif mudah terlihat di kawasan sekitar teluk kini tidak lagi seperti dulu.

Apalagi setelah peristiwa **Smong 2004**, bentang pesisir dan kehidupan masyarakat Simeulue tentu mengalami perubahan besar. Tetapi untuk menghubungkan berkurangnya lobster secara langsung dengan Smong diperlukan penelitian khusus; saya tidak ingin menjadikan ingatan pribadi sebagai kesimpulan ilmiah.

Yang saya tahu, ada masa ketika lobster menjadi bagian dari pemandangan kami di pinggiran Teluk Sinabang.

Dan bagi saya, itu adalah kenangan yang sangat berharga.

