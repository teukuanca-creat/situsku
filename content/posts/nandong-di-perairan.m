Bagi masyarakat luar, Nandong mungkin terdengar asing. Ini adalah seni tutur khas Simeulue yang dilantunkan tanpa instrumen musik. Ritme dan temponya hanya mengandalkan tepukan manual atau hentakan ritmis, dibawakan secara bersahutan oleh para pelantunnya.

​Masyarakat Simeulue tumbuh bersama Nandong. Bagi kami, ia bukan sekadar nyanyian, melainkan sejarah yang dirawat lewat tutur lisan dari satu generasi ke generasi berikutnya. 

Nandong kerap hadir di acara desa atau panggung hiburan, menjadi ruh ketika orang-orang berkumpul di malam hari.

​Namun, tidak semua Nandong lahir dari panggung dan sore itu saya baru benar-benar menyadarinya.

​Saya sedang memancing bersama teman menggunakan perahu mesin di perairan sekitar Pulau Siumat. Saat mesin dimatikan, laut begitu tenang hingga suara sekecil apa pun terdengar jelas. Dari kejauhan, sayup-sayup terdengar lantunan suara.

​Bukan dari pengeras suara atau hajatan warga. Suara itu datang dari perahu lain yang jaraknya cukup jauh. Ada yang bernyanyi tanpa musik, hanya mengandalkan hentakan tangan ke dinding perahu sebagai penjaga tempo.

​Tak... Tak-Tak... tak. tak. tak. tak.

​Iramanya terbawa angin pelan di antara dua pulau, kadang jelas, kadang samar. Irama itu persis seperti yang sering saya dengar di panggung-panggung desa. Namun, mendengarnya langsung di tengah laut lepas memberi sensasi yang sama sekali berbeda. Ada rasa merinding yang sulit dijelaskan, seolah lantunan itu menjadi pintu yang membawa saya melintasi waktu.

​Yang membuat saya makin tertegun, mereka bernyanyi secara bersahutan. Perahu pertama melantunkan bait, lalu disahut oleh perahu kedua. Tanpa panduan, tanpa latihan khusus, mereka seperti sudah paham luar kepala bagian masing-masing. Nandong itu mengalir begitu fasih, mendarah daging, dan alami.

​Di panggung desa, Nandong hadir dengan tata lampu, mikrofon, penonton, dan pakaian khusus. Ada persiapan yang matang di sana. Namun di laut, Nandong tak butuh panggung maupun penonton. Ia hadir di antara desir angin dan ombak, menjadi cara orang-orang mengarungi lautan tanpa merasa kesepian.

​Nandong juga hidup di daratan. Dulu, sewaktu kecil, kami sering mendengarnya dari para pengrajin perahu di tepi pantai, nelayan yang memperbaiki jaring, atau warga yang sedang memetik cengkeh di kebun daerah Kahat, Simeulue Timur. Sambil bekerja, mereka saling bersahutan Nandong, membuat lelah seharian terasa lebih ringan.

​Nandong tidak menunggu festival, anggaran, atau panggung hiburan untuk tetap ada. Ia bertahan karena terus dituturkan dalam keseharian warga, di laut, di kebun, dan di mana saja.

​Jika generasi muda menyadari bahwa Nandong hidup organik di tengah aktivitas keseharian warga, mungkin mereka akan memaknainya secara berbeda. Bukan lagi sekadar warisan budaya yang kaku dan harus dilestarikan di dalam museum atau panggung pertunjukan, melainkan tradisi yang tetap bernapas dan relevan.

​Sore itu di perairan Siumat, saya mendengar Nandong bukan lagi sebagai penonton, melainkan sebagai bagian dari tradisi itu sendiri, sesuatu yang dari dulu ada dan tak pernah benar-benar pergi.
